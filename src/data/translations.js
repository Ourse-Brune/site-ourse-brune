// Fonctions de reconnaissance intelligente de motifs (formats récurrents des céramiques)
export function autoTranslateDimension(str) {
  if (!str) return str
  const s = str.replace(/\u00A0/g, ' ').trim()
  const mCoupe = s.match(/^Coupe\s+de\s+(\d+)\s*cm(?:\s*environ)?$/i)
  if (mCoupe) return `Approx. ${mCoupe[1]} cm bowl`
  const mPlatMural = s.match(/^Plat\s+mural\s+(?:de\s+)?(\d+)\s*cm(?:\s*environ)?$/i)
  if (mPlatMural) return `Approx. ${mPlatMural[1]} cm wall platter`
  const mPlat = s.match(/^Plat\s+de\s+(\d+)\s*cm(?:\s*environ)?$/i)
  if (mPlat) return `Approx. ${mPlat[1]} cm platter`
  const mAssiette = s.match(/^Assiette\s+de\s+(\d+)\s*cm(?:\s*environ)?$/i)
  if (mAssiette) return `Approx. ${mAssiette[1]} cm plate`
  const mDiam = s.match(/^Diam[eè]tre\s+(?:de\s+)?(\d+)\s*cm(?:\s*environ)?$/i)
  if (mDiam) return `Approx. ${mDiam[1]} cm diameter`
  const mEnv = s.match(/^Environ\s+(\d+)\s*cm$/i)
  if (mEnv) return `Approx. ${mEnv[1]} cm`
  return str
}

export function autoTranslateMaterial(str) {
  if (!str) return str
  const s = str.replace(/\u00A0/g, ' ').trim().toLowerCase()
  if (s.includes('faïence blanche') || s.includes('faience blanche')) return 'White earthenware'
  if (s.includes('faïence rouge') || s.includes('faience rouge')) return 'Red earthenware'
  if (s.includes('faïence noire') || s.includes('faience noire')) return 'Black earthenware'
  if (s.includes('grès') || s.includes('gres')) return 'Stoneware'
  if (s.includes('porcelaine')) return 'Porcelain'
  if (s.includes('terre cuite')) return 'Terracotta'
  return str
}

export function autoTranslateEdition(str) {
  if (!str) return str
  const s = str.replace(/\u00A0/g, ' ').trim()
  const mEx = s.match(/^(\d+)\s*exemplaires?$/i)
  if (mEx) return `Edition of ${mEx[1]}`
  if (/^pi[eè]ce\s+unique$/i.test(s) || /^1\s*exemplaire$/i.test(s)) return 'Unique piece'
  const mLim = s.match(/^s[eé]rie\s+limit[eé]e\s+(?:[àa]\s+)?(\d+)\s*exemplaires?$/i)
  if (mLim) return `Limited edition of ${mLim[1]}`
  if (/^s[eé]rie\s+limit[eé]e$/i.test(s)) return 'Limited edition'
  return str
}

export function translatePiece(dish, lang) {
  if (!dish || lang === 'fr') return dish
  const clean = (s) => (s ? String(s).replace(/\u00A0/g, ' ').trim() : '')
  const lookup = (val) => {
    if (!val) return val
    const c = clean(val)
    if (PIECE_TRANSLATIONS[val]?.[lang]) return PIECE_TRANSLATIONS[val][lang]
    if (PIECE_TRANSLATIONS[c]?.[lang]) return PIECE_TRANSLATIONS[c][lang]
    return val
  }

  // Nom / Titre : priorité au champ Sanity titleEn, sinon lookup, sinon titre original
  const translatedName = dish.titleEn || lookup(dish.name) || dish.name

  // Statut
  let translatedStatus = lookup(dish.status)
  if (translatedStatus === dish.status) {
    const s = clean(dish.status).toUpperCase()
    if (s.includes('COMMANDE')) translatedStatus = 'MADE TO ORDER'
    else if (s.includes('DISPONIBLE')) translatedStatus = 'AVAILABLE'
    else if (s.includes('EPUISE') || s.includes('ÉPUISÉ')) translatedStatus = 'SOLD OUT'
  }

  // Type / Dimensions : priorité champ Sanity dimensionsEn, sinon dictionnaire, sinon motif auto
  const rawType = dish.type || ''
  const translatedType =
    dish.dimensionsEn ||
    (PIECE_TRANSLATIONS[rawType]?.[lang] ? PIECE_TRANSLATIONS[rawType][lang] : autoTranslateDimension(rawType))

  // Matière : priorité champ Sanity materialEn, sinon dictionnaire, sinon motif auto
  const rawMat = dish.material || ''
  const translatedMaterial =
    dish.materialEn ||
    (PIECE_TRANSLATIONS[rawMat]?.[lang] ? PIECE_TRANSLATIONS[rawMat][lang] : autoTranslateMaterial(rawMat))

  // Tirage / Édition : priorité champ Sanity exemplairesEn, sinon dictionnaire, sinon motif auto
  const rawEd = dish.edition || ''
  const translatedEdition =
    dish.exemplairesEn ||
    dish.editionEn ||
    (PIECE_TRANSLATIONS[rawEd]?.[lang] ? PIECE_TRANSLATIONS[rawEd][lang] : autoTranslateEdition(rawEd))

  // Description détaillée : priorité champ Sanity descriptionEn, sinon dictionnaire
  const translatedDescription = dish.descriptionEn || lookup(dish.description) || dish.description

  return {
    ...dish,
    name: translatedName,
    type: translatedType,
    material: translatedMaterial,
    edition: translatedEdition,
    status: translatedStatus,
    description: translatedDescription,
  }
}

export function translateSerie(serie, lang) {
  if (!serie || lang === 'fr') return serie
  return {
    ...serie,
    bannerText: serie.bannerTextEn || serie.bannerText || serie.title,
    bannerSubtitle: serie.bannerSubtitleEn || serie.bannerSubtitle,
    description: serie.descriptionEn || PIECE_TRANSLATIONS[serie.description]?.[lang] || serie.description,
    items: serie.items ? serie.items.map((item) => translatePiece(item, lang)) : [],
  }
}
